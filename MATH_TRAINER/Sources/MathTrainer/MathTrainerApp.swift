    private func prepareShopPrices() {
        var prices: [String: Int] = [:]
        var ordinaryIndex = 0
        for item in Collectible.all {
            if item.isRare {
                prices[item.id] = 100
            } else {
                prices[item.id] = 25 + ordinaryIndex
                ordinaryIndex += 1
            }
        }
        shopPricesStorage = prices.keys.sorted().map { "\($0)=\(prices[$0]!)" }.joined(separator: ",")
    }

    private func openShop() {
        prepareShopPrices()
        selected = .shop
    }

